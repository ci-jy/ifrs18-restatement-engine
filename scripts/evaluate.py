"""Evaluate the rules on the labelled corpus and write docs/results.md and docs/accuracy.png.

Usage: python scripts/evaluate.py
"""
from __future__ import annotations

import sys
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

import matplotlib  # noqa: E402

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402

from ifrs18.evaluate import baseline_accuracy, run, summarise  # noqa: E402


def main() -> int:
    results, conserved = run(ROOT / "corpus")
    out = ["# Evaluation on the labelled SEC corpus", "",
           "Generated by `python scripts/evaluate.py`. Labels: `corpus/labels/*.yaml` (written with a rationale per line",
           "before the rules were tuned on the dev split only).", "",
           "| Split | Statements | Lines | Rule accuracy | Naive baseline | Non-operating lines correct | Flagged for review | Errors caught by a flag | Accuracy on unflagged lines | Net income conserved |",
           "|---|---|---|---|---|---|---|---|---|---|"]
    sums = {}
    for split in ("dev", "heldout"):
        s = summarise(results, split)
        sums[split] = s
        b = baseline_accuracy(results, split)
        cons = sum(conserved[sl] for sl in {r.slug for r in results if r.split == split})
        out.append(f"| {split} | {s['statements']} | {s['lines']} | {s['accuracy']:.1%} ({s['correct']}/{s['lines']}) | {b:.1%} | "
                   f"{s['non_operating_correct']}/{s['non_operating_lines']} | {s['flag_share']:.1%} ({s['flagged']}) | "
                   f"{s['errors_flagged']}/{s['errors']} | {s['accuracy_unflagged']:.1%} | {cons}/{s['statements']} |")
    out += ["", "## Held-out errors", "", "| Filer | Line | Label | Label category | Predicted | Rule | Flagged | Ambiguous on the face |", "|---|---|---|---|---|---|---|---|"]
    for r in results:
        if r.split == "heldout" and not r.correct:
            out.append(f"| {r.slug} | {r.line_id} | {r.label} | {r.truth} | {r.predicted} | {r.rule_id} | {'yes' if r.flagged else 'no'} | {'yes' if r.ambiguous else 'no'} |")
    out += ["", "## Held-out accuracy by labelled category", "", "| Category | Lines | Correct |", "|---|---|---|"]
    held = [r for r in results if r.split == "heldout"]
    tot, ok = Counter(r.truth for r in held), Counter(r.truth for r in held if r.correct)
    for cat in ("operating", "investing", "financing", "income_taxes", "discontinued"):
        if tot[cat]:
            out.append(f"| {cat} | {tot[cat]} | {ok[cat]} ({ok[cat] / tot[cat]:.0%}) |")
    (ROOT / "docs").mkdir(exist_ok=True)
    (ROOT / "docs" / "results.md").write_text("\n".join(out) + "\n")

    # figure: accuracy per held-out filer vs naive baseline
    slugs = sorted({r.slug for r in held})
    acc = [sum(r.correct for r in held if r.slug == s) / sum(1 for r in held if r.slug == s) for s in slugs]
    naive = []
    for s in slugs:
        rs = [r for r in held if r.slug == s]
        naive.append(sum((r.predicted if r.predicted in ("income_taxes", "discontinued") else "operating") == r.truth for r in rs) / len(rs))
    fig, ax = plt.subplots(figsize=(10, 4.2))
    x = range(len(slugs))
    ax.bar([i - 0.2 for i in x], naive, 0.4, label="Naive: everything above tax is operating", color="#bbbbbb")
    ax.bar([i + 0.2 for i in x], acc, 0.4, label="IFRS 18 rule engine", color="#2f6db5")
    ax.set_xticks(list(x), [s.replace("_", " ") for s in slugs], rotation=35, ha="right")
    ax.set_ylim(0, 1.25)
    ax.set_ylabel("Lines in the right category")
    h = sums["heldout"]
    ax.set_title(f"Held-out real 20-F income statements: {h['accuracy']:.1%} vs {baseline_accuracy(results, 'heldout'):.1%} naive "
                 f"({h['lines']} lines, {h['statements']} filers)")
    ax.legend(loc="upper center", ncol=2, fontsize=8)
    fig.tight_layout()
    fig.savefig(ROOT / "docs" / "accuracy.png", dpi=120)
    print("\n".join(out[:8]))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
